AllCombComp = table([], [], 'VariableNames', {'Name', 'Stiffness'});

for i = 1: SpringSum
    for j = i: SpringSum
        IComp = springsTable.IfComp(i);
        JComp = springsTable.IfComp(j);
        if (IComp == JComp)
            NewCombIfComp = IComp;
            Name = [springsTable.Name(i),' & ', springsTable.Name(j)];
            NewCombName = {strcat(Name{:})};
            NewStiffness = (springsTable.Stiffness(i) + springsTable.Stiffness(j)) / 2;
            NewComb = table(NewCombName, NewStiffness, 'VariableNames', {'Name', 'Stiffness'});
            if (NewCombIfComp == 0)
                AllCombNotComp = [AllCombNotComp; NewComb];
            else
                AllCombComp = [AllCombComp; NewComb];
            end
        end
    end
end

